-- MySQL 8.0+; database dibuat sebelumnya melalui CREATE DATABASE
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(100) UNIQUE NOT NULL,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(30) NOT NULL DEFAULT 'admin'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS santri (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nis VARCHAR(40) UNIQUE NOT NULL,
 nama VARCHAR(120) NOT NULL, kelas VARCHAR(120) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rekap (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, santri_id BIGINT UNSIGNED NOT NULL,
 bulan VARCHAR(7) NOT NULL, setoran INT NOT NULL, murojaah INT NOT NULL,
 hafalan_tercapai DECIMAL(6,2) NOT NULL, kehadiran DECIMAL(5,2) NOT NULL,
 UNIQUE KEY unique_santri_bulan(santri_id,bulan), FOREIGN KEY(santri_id) REFERENCES santri(id) ON DELETE CASCADE,
 CONSTRAINT ck_setoran CHECK(setoran>=0),CONSTRAINT ck_murojaah CHECK(murojaah>=0),
 CONSTRAINT ck_hafalan CHECK(hafalan_tercapai BETWEEN 0 AND 30),
 CONSTRAINT ck_kehadiran CHECK(kehadiran BETWEEN 0 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS runs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 start_month VARCHAR(7) NOT NULL,end_month VARCHAR(7) NOT NULL,k INT NOT NULL,metrics_json LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS run_items (
 run_id BIGINT UNSIGNED NOT NULL,santri_id BIGINT UNSIGNED NOT NULL,
 cluster INT NOT NULL,setoran DOUBLE NOT NULL,murojaah DOUBLE NOT NULL,
 hafalan_tercapai DOUBLE NOT NULL,kehadiran DOUBLE NOT NULL,
 PRIMARY KEY(run_id,santri_id),FOREIGN KEY(run_id) REFERENCES runs(id) ON DELETE CASCADE,
 FOREIGN KEY(santri_id) REFERENCES santri(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
